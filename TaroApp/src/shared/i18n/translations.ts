export type TranslationKey = string;

export function interpolate(value: string, params?: TranslationParams) {
  if (!params) {
    return value;
  }

  return value.replace(/\{\{(\w+)\}\}/g, (_, key: string) =>
    params[key] === undefined ? "" : String(params[key])
  );
}
